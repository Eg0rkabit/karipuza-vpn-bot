def _escape(value: object) -> str:
    return html.escape(str(value), quote=True)


def _support_contact(settings: Settings) -> tuple[str, str]:
    if settings.legal_support_contact:
        contact = settings.legal_support_contact
        if contact.startswith("@"):
            username = contact.lstrip("@")
            suffix = (
                "?start=support"
                if username.lower() == settings.bot_username.lower()
                else ""
            )
            return (
                f"Связаться со службой поддержки можно в Telegram: @{username}. "
                "Ответ придёт в чат после рассмотрения обращения.",
                f"https://t.me/{username}{suffix}",
            )
        if "@" in contact and " " not in contact:
            return (
                f"Напишите службе поддержки на электронную почту: {contact}.",
                f"mailto:{contact}",
            )
        return f"Контакт службы поддержки: {contact}.", ""
    if settings.bot_username:
        username = settings.bot_username.lstrip("@")
        return (
            f"Связаться со службой поддержки можно через раздел «Поддержка» "
            f"в Telegram-боте @{username}. Ответ придёт в чат после рассмотрения "
            "обращения.",
            f"https://t.me/{username}?start=support",
        )
    return (
        "Связаться со службой поддержки можно через раздел «Поддержка» "
        "в Telegram-боте.",
        "",
    )


def _tariff_rows() -> str:
    return "".join(
        (
            "<tr>"
            f"<td>{_escape(tariff.title)}</td>"
            f"<td>{tariff.days} дней</td>"
            f"<td><strong>{tariff.price_rub} ₽</strong></td>"
            f"<td><del>{tariff.previous_price_rub} ₽</del> "
            f"(−{tariff.discount_percent}%)</td>"
            "<td>без ограничения трафика</td>"
            "<td>до 5 личных устройств</td>"
            "</tr>"
        )
        for tariff in TARIFFS
    )


def _navigation(active: str) -> str:
    links = (
        ("documents", "/documents", "Соглашения"),
        ("privacy", "/privacy", "Конфиденциальность"),
        ("terms", "/terms", "Соглашение"),
    )
    return "".join(
        f'<a class="{"active" if key == active else ""}" href="{url}">{label}</a>'
        for key, url, label in links
    )


def _section(
    title: str, paragraphs: Iterable[str], list_items: Iterable[str] = ()
) -> str:
    body = "".join(f"<p>{paragraph}</p>" for paragraph in paragraphs)
    items = list(list_items)
    if items:
        body += "<ul>" + "".join(f"<li>{item}</li>" for item in items) + "</ul>"
    return f"<section><h2>{title}</h2>{body}</section>"


